const cursosEducacaoPedagogia = nomesEducacaoPedagogia.map((nome) => ({
  nome,
  categoria: categoriaEducacaoPedagogia,
  conteudo: conteudoPadrao
}));

async function seedCursosEducacaoPedagogia() {
  try {
    const dataSource = await initializeDataSource();
    const cursoRepository = dataSource.getRepository(Cursos);

    for (const cursoData of cursosEducacaoPedagogia) {
      const existente = await cursoRepository.findOne({
        where: { nome: cursoData.nome }
      });

      if (existente) {
        console.log(`Curso já existe: ${cursoData.nome}`);
        continue;
      }

      const curso = cursoRepository.create(cursoData);
      await cursoRepository.save(curso);
      console.log(`Criado curso: ${cursoData.nome}`);
    }

    console.log(`Categoria ${categoriaEducacaoPedagogia} criada com sucesso.`);
    console.log(`${cursosEducacaoPedagogia.length} cursos processados.`);
    process.exit(0);
  } catch (error) {
    console.error("Erro ao criar cursos:", error);
    process.exit(1);
  }
}

seedCursosEducacaoPedagogia();
